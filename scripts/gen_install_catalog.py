#!/usr/bin/env python3
"""Generate plugins/village-bridge/_install_catalog.py and skills/mini-apps/SKILL.md from the reviewed catalog.

MINIAPP-INSTALL-LINK (v2.1.5): when a mini-app is not installed, the `village` tool hands the agent that app's
one-tap Mini-apps link, and the agent may suggest the other installable apps. Each name, one line and link
comes from mini-apps/<id>/manifest.json (reviewed in this repository, mirrored by the control plane's
control-plane/src/mini-apps-catalog.js), never from a tool argument, an upstream response or a hand-written list.
A manifest marked `"staff": true` (the cp catalog's `staff: true`, cp#322: Gold Stars, which Rolodex rides) comes with
every agent: it is written to STAFF with no installUrl and is never listed as installable. A manifest marked
`"listed": false` is skipped before any check and appears in neither output.

    python3 scripts/gen_install_catalog.py          # rewrite the module
    python3 scripts/gen_install_catalog.py --check  # exit 1 when either output is stale

The skill's words come from plugins/village-bridge/_install_copy.py (product's strings, one place).
plugins/village-bridge/tests/test_install_link.py fails while either committed output differs from this.
"""
from __future__ import annotations

import importlib.util
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
MANIFESTS = REPO / "mini-apps"
OUTPUT = REPO / "plugins" / "village-bridge" / "_install_catalog.py"
COPY = REPO / "plugins" / "village-bridge" / "_install_copy.py"
SKILL = REPO / "skills" / "mini-apps" / "SKILL.md"
# The app's Mini-apps page opens one app's sheet from `?app=<appId>` (Edge-City/agentvillage-app main:
# src/lib/mini-apps/client.ts readMiniAppsQuery reads `app`; src/components/mini-apps/MiniAppsPage.tsx
# entryIn(value, query.app) opens that app's sheet). The origin and path are fixed here, never derived.
MINI_APPS_PAGE = "https://agents.edgecity.live/mini-apps?app="
APP_ID = re.compile(r"[a-z][a-z0-9-]{0,63}")
# One line of plain catalog prose: no link, markup or control character can ride into the agent's words.
MARKUP = frozenset("<>[]{}()`*_|#\\")


def plain(value: object) -> bool:
    return (isinstance(value, str) and 0 < len(value) <= 160 and value == value.strip() and value.isprintable()
            and not MARKUP & set(value) and "://" not in value and "www." not in value.lower())


def entries(manifests: Path = MANIFESTS) -> list[dict]:
    apps = []
    for path in sorted(manifests.glob("*/manifest.json")):
        doc = json.loads(path.read_text(encoding="utf-8"))
        # UNLISTED (product L14133, ov#416 S1): `"listed": false` keeps a reviewed app out of every install surface.
        # It is skipped BEFORE any other check, so its name and description are never read, and it never reaches
        # INSTALLABLE, STAFF, the skill's examples, the general list or the installable list. Absent or true = listed.
        listed = doc.get("listed", True) if isinstance(doc, dict) else True
        if listed is False:
            continue
        if listed is not True:
            raise ValueError(f"{path}: listed must be false or absent")
        app_id, name, description = doc.get("id"), doc.get("name"), doc.get("description")
        if not isinstance(app_id, str) or not APP_ID.fullmatch(app_id) or app_id != path.parent.name:
            raise ValueError(f"{path}: id must be the directory name and match {APP_ID.pattern}")
        for field, value in (("name", name), ("description", description)):
            if not plain(value):
                raise ValueError(f"{path}: {field} must be one line of plain catalog text")
        # STAFF APPS (lead L13438, product L13443; cp#322 `staff: true`, absent = false): an app that comes with
        # every agent. It can be neither installed nor removed, so it never gets an install link.
        staff = doc.get("staff", False)
        if staff is not True and staff is not False:
            raise ValueError(f"{path}: staff must be true or absent")
        app = {"id": app_id, "name": name, "description": description}
        apps.append(app if staff else {**app, "installUrl": MINI_APPS_PAGE + app_id})
    if not apps:
        raise ValueError(f"no manifests under {manifests}")
    return apps


def split(apps: list[dict]) -> tuple[list[dict], list[dict]]:
    """(installable, staff): a staff entry is the one without an installUrl."""
    return [app for app in apps if "installUrl" in app], [app for app in apps if "installUrl" not in app]


def render(apps: list[dict]) -> str:
    installable, staff = split(apps)
    def rows(entries: list[dict]) -> str:
        return "".join("    " + json.dumps(app, ensure_ascii=False) + ",\n" for app in entries)
    return (
        '"""GENERATED by scripts/gen_install_catalog.py from mini-apps/*/manifest.json. Do not edit by hand:\n'
        'change a reviewed manifest, then run `python3 scripts/gen_install_catalog.py`."""\n'
        f"MINI_APPS_PAGE = {json.dumps(MINI_APPS_PAGE)}\n"
        "INSTALLABLE = (\n" + rows(installable) + ")\n"
        "# Apps that come with every agent (manifest `staff: true`): no installUrl, never an install link.\n"
        "STAFF = (\n" + rows(staff) + ")\n"
    )


def product_copy(path: Path = COPY):
    """Product's strings (_install_copy.py: plain assignments, no imports), loaded from the file."""
    spec = importlib.util.spec_from_file_location("_install_copy", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def render_skill(apps: list[dict], words) -> str:
    """skills/mini-apps/SKILL.md: product's words around the catalog's apps, nothing hand-written per app."""
    def fill(template: str, app: dict) -> str:
        return template.format(name=app["name"], description=app["description"], link=app.get("installUrl", ""))
    installable, staff = split(apps)
    if not installable:
        raise ValueError("no installable app in the catalog")
    sample = next((app for app in installable if app["id"] == "forkicks"), installable[0])
    lines = "\n".join("- " + fill(words.LINE, app) for app in installable)
    general = "\n".join("> " + line for line in [words.GENERAL_INTRO, *(fill(words.LINE, app) for app in installable), words.GENERAL_OUTRO])
    staff_section = (
        "## Apps that come with every agent\n\n"
        f"{words.STAFF_INTRO}\n\n"
        + "\n".join("- " + fill(words.STAFF_ROW, app) for app in staff) + "\n\n"
        f"{words.STAFF_RULE}\n\n"
        + "\n".join("> " + fill(words.STAFF_TELL, app) for app in staff[:1]) + "\n\n"
    ) if staff else ""
    return (
        "---\n"
        "name: mini-apps\n"
        f"description: {words.SKILL_DESCRIPTION}\n"
        "version: 1.0.0\n"
        "author: Edge City\n"
        "---\n\n"
        "<!-- GENERATED by scripts/gen_install_catalog.py from plugins/village-bridge/_install_copy.py (product's words)\n"
        "     and mini-apps/*/manifest.json (the reviewed catalog). Do not edit by hand. -->\n\n"
        "# Mini-apps\n\n"
        f"{words.RULE}\n\n"
        f"{words.SKILL_OFFER}\n\n"
        "## Three situations\n\n"
        "1. The resident names an app that isn't installed, for example:\n\n"
        f"> {fill(words.NAMED, sample)}\n\n"
        "2. The resident asks generally (install mini-apps, what apps can you use?): one intro line, then each app "
        "they can open on its own line, unranked:\n\n"
        f"{general}\n\n"
        "3. An action fails because its app isn't installed: name the app the action needs (the `village` answer's "
        "`appName`), never the error, for example:\n\n"
        f"> {fill(words.MID_TASK, sample)}\n\n"
        f"{words.NEVER}\n\n"
        f"{staff_section}"
        "## Installable apps\n\n"
        "From the reviewed catalog. Offer only the ones this resident can open (above).\n\n"
        f"{lines}\n"
    )


def outputs() -> dict:
    apps = entries()
    return {OUTPUT: render(apps), SKILL: render_skill(apps, product_copy())}


def main(argv: list[str]) -> int:
    texts = outputs()
    if argv[1:] == ["--check"]:
        stale = [path for path, text in texts.items() if (path.read_text(encoding="utf-8") if path.exists() else "") != text]
        for path in stale:
            print(f"{path.relative_to(REPO)} is stale: run python3 scripts/gen_install_catalog.py", file=sys.stderr)
        return 1 if stale else 0
    if argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    for path, text in texts.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
